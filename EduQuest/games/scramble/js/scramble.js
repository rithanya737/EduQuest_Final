const urlParams = new URLSearchParams(window.location.search);

const topic = urlParams.get("topic");

const words = scrambleData[topic];

let selectedWords = [];

while (selectedWords.length < 5) {
    let randomIndex = Math.floor(Math.random() * words.length);
    if (!selectedWords.includes(words[randomIndex])) {
        selectedWords.push(words[randomIndex]);
    }
}

const topicTitle = document.getElementById("topic-title");

const wordNumber = document.getElementById("word-number");

const scrambledWord = document.getElementById("scrambled-word");

const hearts = document.getElementById("hearts");

const answerInput = document.getElementById("answer");

const submitButton = document.getElementById("submit-button");

const nextButton = document.getElementById("next-button");

const hint1 = document.getElementById("hint1");

const hint2 = document.getElementById("hint2");

const hintText = document.getElementById("hint-text");

let currentWordIndex = 0;

let currentWord = selectedWords[0];

let score = 0;

let attempts = 3;

let answered = false;

function scrambleWord(word) {
    let letters = word.split("");
    letters.sort(function() {
        return Math.random() - .5;
    });
    return letters.join("");
}

const topicNames = {
    science: "Indian Science & Technology",
    monuments: "Indian Monuments & Architecture",
    languages: "Indian Languages & Literature",
    economy: "Indian Economy & Finance",
    environment: "Indian Environment & Wildlife",
    education: "Indian Education & Institutions"
};

topicTitle.innerHTML = topicNames[topic];

function displayWord() {
    currentWord = selectedWords[currentWordIndex];
    wordNumber.innerHTML = "Word " + (currentWordIndex + 1) + " of 5";
    scrambledWord.innerHTML = scrambleWord(currentWord.word);
}

displayWord();

submitButton.addEventListener("click", function() {
    if (answered) {
        return;
    }
    let answer = answerInput.value.trim().toUpperCase();
    if (answer === "") {
        hintText.innerHTML = "Please enter an answer!";
        return;
    }
    if (answer === currentWord.word.toUpperCase()) {
        score++;
        answered = true;
        hintText.innerHTML = "Correct! 🎉";
    } else {
        attempts--;
        hearts.innerHTML = "💔 ".repeat(3 - attempts) + "❤️ ".repeat(attempts);
        if (attempts === 0) {
            answered = true;
            hintText.innerHTML = "No attempts left! ❌";
        } else {
            hintText.innerHTML = "Wrong answer! Try again.";
        }
    }
});

hint1.addEventListener("click", function() {
    hintText.innerHTML = currentWord.hint1;
    hint1.disabled = true;
});

hint2.addEventListener("click", function() {
    hintText.innerHTML = currentWord.hint2;
    hint2.disabled = true;
});

nextButton.addEventListener("click", function() {
    if (!answered) {
        hintText.innerHTML = "Please answer the word first!";
        return;
    }
    currentWordIndex++;
    if (currentWordIndex === 5) {
        gameFinished();
        return;
    }
    displayWord();
    attempts = 3;
    hearts.innerHTML = "❤️ ❤️ ❤️";
    answered = false;
    hint1.disabled = false;
    hint2.disabled = false;
    hintText.innerHTML = "";
    answerInput.value = "";
});

const gameContainer = document.querySelector(".game-container");

const resultPage = document.getElementById("result-page");

const finalTopic = document.getElementById("final-topic");

const finalScore = document.getElementById("final-score");

function gameFinished() {
    if (typeof EduQuestData !== "undefined") EduQuestData.saveScore("scramble", score);
    gameContainer.style.display = "none";
    resultPage.style.display = "block";
    finalTopic.innerHTML = topicNames[topic];
    finalScore.innerHTML = "Your Score: " + score + " / 5";
}

