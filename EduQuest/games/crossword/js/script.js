const WORDS_PER_ROUND = 12;

const MIN_WORDS_TO_ACCEPT = 7;

const GRID_SIZE = 40;

const CENTER = 20;

let usedWords = new Set;

let placedWords = [];

let cellMap = {};

let selectedCell = null;

let selectedDirection = "across";

let secondsElapsed = 0;

let timerId = null;

let totalCells = 0;

function shuffle(arr) {
    const copy = arr.slice();
    for (let i = copy.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        const tmp = copy[i];
        copy[i] = copy[j];
        copy[j] = tmp;
    }
    return copy;
}

function pickRoundWords() {
    let available = WORD_BANK.filter(function(w) {
        return !usedWords.has(w.word);
    });
    if (available.length < WORDS_PER_ROUND) {
        usedWords.clear();
        available = WORD_BANK.slice();
    }
    const chosen = shuffle(available).slice(0, WORDS_PER_ROUND);
    chosen.forEach(function(w) {
        usedWords.add(w.word);
    });
    return chosen;
}

function makeEmptyGrid() {
    const grid = [];
    for (let r = 0; r < GRID_SIZE; r++) {
        grid.push(new Array(GRID_SIZE).fill(null));
    }
    return grid;
}

function canPlaceWord(grid, word, row, col, dir) {
    const len = word.length;
    const endRow = dir === "down" ? row + len - 1 : row;
    const endCol = dir === "across" ? col + len - 1 : col;
    if (row < 1 || col < 1 || endRow > GRID_SIZE - 2 || endCol > GRID_SIZE - 2) {
        return false;
    }
    if (dir === "across") {
        if (grid[row][col - 1] || grid[row][col + len]) return false;
    } else {
        if (grid[row - 1][col] || grid[row + len][col]) return false;
    }
    for (let k = 0; k < len; k++) {
        const r = dir === "down" ? row + k : row;
        const c = dir === "across" ? col + k : col;
        const existing = grid[r][c];
        if (existing) {
            if (existing.letter !== word[k]) return false;
        } else {
            if (dir === "across") {
                if (grid[r - 1][c] || grid[r + 1][c]) return false;
            } else {
                if (grid[r][c - 1] || grid[r][c + 1]) return false;
            }
        }
    }
    return true;
}

function placeWordOnGrid(grid, wordObj, row, col, dir) {
    for (let k = 0; k < wordObj.word.length; k++) {
        const r = dir === "down" ? row + k : row;
        const c = dir === "across" ? col + k : col;
        if (!grid[r][c]) grid[r][c] = {
            letter: wordObj.word[k]
        };
    }
    return {
        word: wordObj.word,
        clue: wordObj.clue,
        row: row,
        col: col,
        dir: dir
    };
}

function tryGeneratePuzzle(roundWords) {
    const grid = makeEmptyGrid();
    const placed = [];
    const sorted = roundWords.slice().sort(function(a, b) {
        return b.word.length - a.word.length;
    });
    const first = sorted[0];
    const startCol = CENTER - Math.floor(first.word.length / 2);
    placed.push(placeWordOnGrid(grid, first, CENTER, startCol, "across"));
    for (let i = 1; i < sorted.length; i++) {
        const candidate = sorted[i];
        let bestPlacement = null;
        for (let li = 0; li < candidate.word.length && !bestPlacement; li++) {
            const letter = candidate.word[li];
            for (let r = 0; r < GRID_SIZE && !bestPlacement; r++) {
                for (let c = 0; c < GRID_SIZE && !bestPlacement; c++) {
                    const cell = grid[r][c];
                    if (!cell || cell.letter !== letter) continue;
                    const dirsToTry = [ "across", "down" ];
                    for (let d = 0; d < dirsToTry.length; d++) {
                        const dir = dirsToTry[d];
                        const row = dir === "down" ? r - li : r;
                        const col = dir === "across" ? c - li : c;
                        if (canPlaceWord(grid, candidate.word, row, col, dir)) {
                            bestPlacement = {
                                row: row,
                                col: col,
                                dir: dir
                            };
                            break;
                        }
                    }
                }
            }
        }
        if (bestPlacement) {
            placed.push(placeWordOnGrid(grid, candidate, bestPlacement.row, bestPlacement.col, bestPlacement.dir));
        }
    }
    return {
        grid: grid,
        placed: placed
    };
}

function generatePuzzle() {
    let result = null;
    for (let attempt = 0; attempt < 6; attempt++) {
        const roundWords = pickRoundWords();
        result = tryGeneratePuzzle(roundWords);
        if (result.placed.length >= MIN_WORDS_TO_ACCEPT) break;
    }
    return trimAndNumber(result.grid, result.placed);
}

function trimAndNumber(grid, placed) {
    let minR = GRID_SIZE, maxR = 0, minC = GRID_SIZE, maxC = 0;
    for (let r = 0; r < GRID_SIZE; r++) {
        for (let c = 0; c < GRID_SIZE; c++) {
            if (grid[r][c]) {
                if (r < minR) minR = r;
                if (r > maxR) maxR = r;
                if (c < minC) minC = c;
                if (c > maxC) maxC = c;
            }
        }
    }
    const trimmed = [];
    for (let r = minR; r <= maxR; r++) {
        const row = [];
        for (let c = minC; c <= maxC; c++) {
            row.push(grid[r][c]);
        }
        trimmed.push(row);
    }
    const adjustedWords = placed.map(function(w) {
        return {
            word: w.word,
            clue: w.clue,
            dir: w.dir,
            row: w.row - minR,
            col: w.col - minC
        };
    });
    let num = 1;
    const rows = trimmed.length;
    const cols = trimmed[0].length;
    const numberAt = {};
    for (let r = 0; r < rows; r++) {
        for (let c = 0; c < cols; c++) {
            if (!trimmed[r][c]) continue;
            const startsAcross = (c === 0 || !trimmed[r][c - 1]) && (c + 1 < cols && trimmed[r][c + 1]);
            const startsDown = (r === 0 || !trimmed[r - 1][c]) && (r + 1 < rows && trimmed[r + 1][c]);
            if (startsAcross || startsDown) {
                numberAt[r + "," + c] = num;
                num++;
            }
        }
    }
    adjustedWords.forEach(function(w) {
        w.number = numberAt[w.row + "," + w.col];
    });
    return {
        grid: trimmed,
        rows: rows,
        cols: cols,
        words: adjustedWords
    };
}

function renderGrid(puzzle) {
    const table = document.getElementById("crossword-grid");
    table.innerHTML = "";
    cellMap = {};
    totalCells = 0;
    for (let r = 0; r < puzzle.rows; r++) {
        const tr = document.createElement("tr");
        for (let c = 0; c < puzzle.cols; c++) {
            const td = document.createElement("td");
            const cellData = puzzle.grid[r][c];
            if (!cellData) {
                td.className = "block";
                tr.appendChild(td);
                continue;
            }
            totalCells++;
            const wrap = document.createElement("div");
            wrap.className = "cell-wrap";
            const numberForCell = findNumberForCell(puzzle, r, c);
            if (numberForCell) {
                const span = document.createElement("span");
                span.className = "cell-number";
                span.textContent = numberForCell;
                wrap.appendChild(span);
            }
            const input = document.createElement("input");
            input.type = "text";
            input.maxLength = 1;
            input.className = "cell-input";
            input.dataset.row = r;
            input.dataset.col = c;
            input.dataset.answer = cellData.letter;
            input.setAttribute("id", "cell-" + r + "-" + c);
            input.setAttribute("autocomplete", "off");
            wrap.appendChild(input);
            td.appendChild(wrap);
            tr.appendChild(td);
            cellMap[r + "," + c] = {
                input: input,
                words: []
            };
        }
        table.appendChild(tr);
    }
    puzzle.words.forEach(function(w) {
        for (let k = 0; k < w.word.length; k++) {
            const r = w.dir === "down" ? w.row + k : w.row;
            const c = w.dir === "across" ? w.col + k : w.col;
            const key = r + "," + c;
            if (cellMap[key]) cellMap[key].words.push(w);
        }
    });
    attachCellEvents();
}

function findNumberForCell(puzzle, r, c) {
    for (let i = 0; i < puzzle.words.length; i++) {
        if (puzzle.words[i].row === r && puzzle.words[i].col === c) {
            return puzzle.words[i].number;
        }
    }
    return null;
}

function renderClues(puzzle) {
    const acrossList = document.getElementById("across-clues");
    const downList = document.getElementById("down-clues");
    acrossList.innerHTML = "";
    downList.innerHTML = "";
    const acrossWords = puzzle.words.filter(function(w) {
        return w.dir === "across";
    }).sort(function(a, b) {
        return a.number - b.number;
    });
    const downWords = puzzle.words.filter(function(w) {
        return w.dir === "down";
    }).sort(function(a, b) {
        return a.number - b.number;
    });
    function buildItem(w) {
        const li = document.createElement("li");
        li.value = w.number;
        const a = document.createElement("a");
        a.href = "#cell-" + w.row + "-" + w.col;
        a.textContent = w.clue + " (" + w.word.length + ")";
        a.dataset.row = w.row;
        a.dataset.col = w.col;
        a.dataset.dir = w.dir;
        a.addEventListener("click", function(e) {
            e.preventDefault();
            selectWord(w);
        });
        li.appendChild(a);
        return li;
    }
    acrossWords.forEach(function(w) {
        acrossList.appendChild(buildItem(w));
    });
    downWords.forEach(function(w) {
        downList.appendChild(buildItem(w));
    });
}

function clearActiveHighlight() {
    document.querySelectorAll(".cell-input.active-word").forEach(function(el) {
        el.classList.remove("active-word");
    });
    document.querySelectorAll(".clue-list a.selected-clue").forEach(function(el) {
        el.classList.remove("selected-clue");
    });
}

function highlightWord(w) {
    clearActiveHighlight();
    for (let k = 0; k < w.word.length; k++) {
        const r = w.dir === "down" ? w.row + k : w.row;
        const c = w.dir === "across" ? w.col + k : w.col;
        const entry = cellMap[r + "," + c];
        if (entry) entry.input.classList.add("active-word");
    }
    const link = document.querySelector('a[data-row="' + w.row + '"][data-col="' + w.col + '"][data-dir="' + w.dir + '"]');
    if (link) link.classList.add("selected-clue");
}

function selectWord(w) {
    selectedDirection = w.dir;
    selectedCell = {
        row: w.row,
        col: w.col
    };
    highlightWord(w);
    const first = cellMap[w.row + "," + w.col];
    if (first) first.input.focus();
}

function wordAt(row, col, dir) {
    const entry = cellMap[row + "," + col];
    if (!entry) return null;
    return entry.words.find(function(w) {
        return w.dir === dir;
    }) || entry.words[0];
}

function attachCellEvents() {
    Object.keys(cellMap).forEach(function(key) {
        const input = cellMap[key].input;
        input.addEventListener("focus", function() {
            const r = Number(input.dataset.row);
            const c = Number(input.dataset.col);
            selectedCell = {
                row: r,
                col: c
            };
            const entry = cellMap[key];
            const preferred = entry.words.find(function(w) {
                return w.dir === selectedDirection;
            });
            const w = preferred || entry.words[0];
            if (w) highlightWord(w);
        });
        input.addEventListener("input", function() {
            input.value = input.value.replace(/[^a-zA-Z]/g, "").toUpperCase().slice(0, 1);
            input.classList.remove("correct", "incorrect");
            if (input.value) moveToAdjacentCell(input, 1);
        });
        input.addEventListener("keydown", function(e) {
            const r = Number(input.dataset.row);
            const c = Number(input.dataset.col);
            if (e.key === "Backspace" && !input.value) {
                moveToAdjacentCell(input, -1);
            } else if (e.key === "ArrowRight") {
                focusCell(r, c + 1);
            } else if (e.key === "ArrowLeft") {
                focusCell(r, c - 1);
            } else if (e.key === "ArrowDown") {
                focusCell(r + 1, c);
            } else if (e.key === "ArrowUp") {
                focusCell(r - 1, c);
            }
        });
    });
}

function focusCell(r, c) {
    const entry = cellMap[r + "," + c];
    if (entry) entry.input.focus();
}

function moveToAdjacentCell(input, delta) {
    const r = Number(input.dataset.row);
    const c = Number(input.dataset.col);
    if (selectedDirection === "across") {
        focusCell(r, c + delta);
    } else {
        focusCell(r + delta, c);
    }
}

function checkAnswers() {
    let correctCount = 0;
    let filledCount = 0;
    Object.keys(cellMap).forEach(function(key) {
        const entry = cellMap[key];
        const val = entry.input.value.toUpperCase();
        if (val) filledCount++;
        if (val === entry.input.dataset.answer) {
            entry.input.classList.add("correct");
            entry.input.classList.remove("incorrect");
            correctCount++;
        } else if (val) {
            entry.input.classList.add("incorrect");
            entry.input.classList.remove("correct");
        }
    });
    const score = correctCount * 10;
    document.getElementById("score").textContent = score;
    document.getElementById("feedback-msg").textContent = correctCount + " / " + totalCells + " letters correct so far.";
    markSolvedClues();
    if (correctCount === totalCells) {
        if (!scoreSaved && typeof EduQuestData !== "undefined") { scoreSaved = true; EduQuestData.saveScore("crossword", score); }
        stopTimer();
        const timeStr = document.getElementById("timer").textContent;
        const playAgain = confirm("Well done! You solved the crossword in " + timeStr + " with a score of " + score + ".\n\nClick OK to start a new puzzle, or Cancel to keep this grid on screen.");
        if (playAgain) newPuzzle(true);
    }
}

function markSolvedClues() {
    document.querySelectorAll(".clue-list a").forEach(function(a) {
        const r = Number(a.dataset.row);
        const c = Number(a.dataset.col);
        const dir = a.dataset.dir;
        const word = puzzleWordFor(r, c, dir);
        if (!word) return;
        let solved = true;
        for (let k = 0; k < word.word.length; k++) {
            const rr = dir === "down" ? word.row + k : word.row;
            const cc = dir === "across" ? word.col + k : word.col;
            const entry = cellMap[rr + "," + cc];
            if (!entry || entry.input.value.toUpperCase() !== entry.input.dataset.answer) {
                solved = false;
                break;
            }
        }
        a.classList.toggle("solved", solved);
    });
}

function puzzleWordFor(row, col, dir) {
    return currentPuzzle.words.find(function(w) {
        return w.row === row && w.col === col && w.dir === dir;
    });
}

function revealLetter() {
    let target = selectedCell;
    if (!target) {
        const answer = prompt("Enter the clue number you would like a hint for:");
        if (answer === null) return;
        const num = parseInt(answer, 10);
        const word = currentPuzzle.words.find(function(w) {
            return w.number === num;
        });
        if (!word) {
            alert("No clue with that number in this puzzle.");
            return;
        }
        target = {
            row: word.row,
            col: word.col
        };
    }
    const entry = cellMap[target.row + "," + target.col];
    if (!entry) return;
    entry.input.value = entry.input.dataset.answer;
    entry.input.classList.add("correct");
    entry.input.classList.remove("incorrect");
    const score = document.getElementById("score");
    score.textContent = Math.max(0, Number(score.textContent) - 5);
}

function startTimer() {
    secondsElapsed = 0;
    updateTimerDisplay();
    timerId = setInterval(function() {
        secondsElapsed++;
        updateTimerDisplay();
    }, 1e3);
}

function stopTimer() {
    clearInterval(timerId);
}

function updateTimerDisplay() {
    const mins = Math.floor(secondsElapsed / 60);
    const secs = secondsElapsed % 60;
    const pad = function(n) {
        return n < 10 ? "0" + n : String(n);
    };
    document.getElementById("timer").textContent = pad(mins) + ":" + pad(secs);
}

let currentPuzzle = null;
let scoreSaved = false;

function newPuzzle(skipConfirm) {
    if (!skipConfirm) {
        const ok = confirm("Start a new puzzle? Your current progress on this grid will be lost.");
        if (!ok) return;
    }
    stopTimer();
    currentPuzzle = generatePuzzle();
    scoreSaved = false;
    renderGrid(currentPuzzle);
    renderClues(currentPuzzle);
    document.getElementById("word-count").textContent = currentPuzzle.words.length + " / " + WORDS_PER_ROUND;
    document.getElementById("score").textContent = "0";
    document.getElementById("feedback-msg").textContent = "";
    selectedCell = null;
    selectedDirection = "across";
    startTimer();
    if (currentPuzzle.words.length > 0) {
        selectWord(currentPuzzle.words[0]);
    }
}

const NAME_PATTERN = /^[A-Za-z][A-Za-z ]{1,29}$/;

document.getElementById("name-form").addEventListener("submit", function(e) {
    e.preventDefault();
    const nameInput = document.getElementById("player-name");
    const errorEl = document.getElementById("name-error");
    const name = nameInput.value.trim();
    if (!NAME_PATTERN.test(name)) {
        errorEl.textContent = "Please enter a name using letters only (2-30 characters).";
        return;
    }
    errorEl.textContent = "";
    document.getElementById("player-name-display").textContent = name;
    document.getElementById("start-screen").classList.add("hidden");
    document.getElementById("game-screen").classList.remove("hidden");
    newPuzzle(true);
});

