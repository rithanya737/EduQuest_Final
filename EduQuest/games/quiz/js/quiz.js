const urlParams = new URLSearchParams(window.location.search);

const topic = urlParams.get("topic");

let questions = quizData[topic];

const quizTitle = document.getElementById("quiz-title");

if (topic === "geography") {
    quizTitle.innerHTML = "Indian Geography Quiz";
} else if (topic === "history") {
    quizTitle.innerHTML = "Indian History Quiz";
} else if (topic === "polity") {
    quizTitle.innerHTML = "Indian Polity Quiz";
} else if (topic === "culture") {
    quizTitle.innerHTML = "Indian Culture & Heritage Quiz";
} else if (topic === "sports") {
    quizTitle.innerHTML = "Indian Sports Quiz";
} else if (topic === "gk") {
    quizTitle.innerHTML = "India General Knowledge Quiz";
}

let selectedquestions = [];

while (selectedquestions.length < 10) {
    let randomindex = Math.floor(Math.random() * questions.length);
    let randomquestion = questions[randomindex];
    if (!selectedquestions.includes(randomquestion)) {
        selectedquestions.push(randomquestion);
    }
}

const questionElement = document.getElementById("question");

const option1 = document.getElementById("option1");

const option2 = document.getElementById("option2");

const option3 = document.getElementById("option3");

const option4 = document.getElementById("option4");

const questionNumber = document.getElementById("question-number");

let currentQuestion = selectedquestions[0];

questionElement.innerHTML = currentQuestion.question;

option1.innerHTML = currentQuestion.options[0];

option2.innerHTML = currentQuestion.options[1];

option3.innerHTML = currentQuestion.options[2];

option4.innerHTML = currentQuestion.options[3];

let score = 0;

let answered = false;

function checkAnswer(selectedOption, clickedButton) {
    if (answered) {
        return;
    }
    answered = true;
    if (selectedOption === currentQuestion.answer) {
        score++;
        clickedButton.style.backgroundColor = "#66bb6a";
        clickedButton.style.color = "white";
        console.log("Correct!");
    } else {
        clickedButton.style.backgroundColor = "#ef5350";
        clickedButton.style.color = "white";
        console.log("Wrong!");
    }
}

option1.addEventListener("click", function() {
    checkAnswer(option1.innerHTML, option1);
});

option2.addEventListener("click", function() {
    checkAnswer(option2.innerHTML, option2);
});

option3.addEventListener("click", function() {
    checkAnswer(option3.innerHTML, option3);
});

option4.addEventListener("click", function() {
    checkAnswer(option4.innerHTML, option4);
});

function resetOptions() {
    option1.style.backgroundColor = "white";
    option2.style.backgroundColor = "white";
    option3.style.backgroundColor = "white";
    option4.style.backgroundColor = "white";
    option1.style.color = "#333";
    option2.style.color = "#333";
    option3.style.color = "#333";
    option4.style.color = "#333";
}

let currentQuestionIndex = 0;

const nextButton = document.getElementById("next-button");

nextButton.addEventListener("click", function() {
    if (currentQuestionIndex === 9) {
        quizFinished();
    } else {
        currentQuestionIndex++;
        currentQuestion = selectedquestions[currentQuestionIndex];
        answered = false;
        resetOptions();
        questionNumber.innerHTML = "Question " + (currentQuestionIndex + 1) + " of 10";
        questionElement.innerHTML = currentQuestion.question;
        option1.innerHTML = currentQuestion.options[0];
        option2.innerHTML = currentQuestion.options[1];
        option3.innerHTML = currentQuestion.options[2];
        option4.innerHTML = currentQuestion.options[3];
    }
});

function quizFinished() {
    if (typeof EduQuestData !== "undefined") EduQuestData.saveScore("quiz", score);
    questionElement.innerHTML = "🎉 Quiz Completed!";
    option1.style.display = "none";
    option2.style.display = "none";
    option3.style.display = "none";
    option4.style.display = "none";
    nextButton.style.display = "none";
    const scoreElement = document.getElementById("score");
    scoreElement.innerHTML = "Your Score: " + score + " / 10";
    scoreElement.style.display = "inline-block";
}

